-- MAGIC # Recap
-- MAGIC
-- MAGIC ## Part 1-2: creating and changing
-- MAGIC | Command | Why it matters |
-- MAGIC |---|---|
-- MAGIC | `CREATE TABLE` | Delta by default; identity columns, `NOT NULL`, Change Data Feed |
-- MAGIC | `INSERT` | All-or-nothing writes — never a half-loaded table |
-- MAGIC | `UPDATE` / `DELETE` | Row-level change; makes GDPR erasure practical |
-- MAGIC | `MERGE` | Apply updates *and* inserts atomically |
-- MAGIC
-- MAGIC ## Part 3: history
-- MAGIC | Command | Use it for |
-- MAGIC |---|---|
-- MAGIC | `DESCRIBE HISTORY` | Who changed what, when, how many rows |
-- MAGIC | `VERSION AS OF` / `@v1` | Exact, reproducible access to a known state |
-- MAGIC | Join two versions | See precisely what changed between two points |
-- MAGIC | `table_changes()` | Row-level before/after; feed downstream systems |
-- MAGIC
-- MAGIC ## Part 4: recovery
-- MAGIC | Strategy | Use when | Main risk |
-- MAGIC |---|---|---|
-- MAGIC | Full `RESTORE` | Whole table wrong, nothing good since | Discards later legitimate changes |
-- MAGIC | Surgical `MERGE` | Some rows wrong, good work must survive | Needs a key to match on |
-- MAGIC | `UNDROP TABLE` | Table was dropped | 7-day window; managed only |
-- MAGIC | Clone checkpoint | Before a risky change | Shallow clone breaks if source vacuumed |
-- MAGIC | Blue/green swap | Rebuild with zero bad visibility | Needs storage for two copies |
-- MAGIC
-- MAGIC ## Part 5-6: evolving and maintaining
-- MAGIC | Command | Why |
-- MAGIC |---|---|
-- MAGIC | `ALTER TABLE ADD COLUMN` | Evolve deliberately, without a rebuild |
-- MAGIC | `CHECK` constraint | Bad data refused at the table, for every writer |
-- MAGIC | `OPTIMIZE` / `ZORDER` | Fix small files; skip files on read |
-- MAGIC | Retention properties | Decide how far back you can go — before you need it |
-- MAGIC | `VACUUM` | Reclaim storage, at the cost of time travel |
-- MAGIC
-- MAGIC ## Three rules worth remembering
-- MAGIC 1. **Note the version number before any risky change.** Cheapest insurance there is.
-- MAGIC 2. **Match the fix to the damage.** Restoring a whole table to repair forty rows
-- MAGIC    destroys everyone else's work since.
-- MAGIC 3. **Rehearse on a clone.** A real incident is the wrong moment for your first
-- MAGIC    attempt at a command.
-- MAGIC
-- MAGIC ### The one-sentence takeaway
-- MAGIC **Delta gives files in cloud storage the guarantees of a database — transactions,
-- MAGIC row-level changes, a full history and several ways to undo — so the lakehouse is
-- MAGIC somewhere you can safely run the business, not just store its data.**

