-- MAGIC %md
-- MAGIC # Part 1 — Creating a Delta table
-- MAGIC
-- MAGIC ## Why Delta at all?
-- MAGIC Every table in Databricks is a **Delta table** by default. Delta is what makes a
-- MAGIC folder of files in cloud storage behave like a real database table:
-- MAGIC
-- MAGIC | Without Delta | With Delta |
-- MAGIC |---|---|
-- MAGIC | To change one row, rewrite everything | `UPDATE` / `DELETE` / `MERGE` |
-- MAGIC | A failed job leaves half-written data | Writes are all-or-nothing |
-- MAGIC | Overwrite a file and yesterday is gone | Every version is kept |
-- MAGIC | Wrong-shaped data lands silently | Schema is enforced |
-- MAGIC
-- MAGIC Those four properties are what the rest of this notebook is built on.

-- COMMAND ----------

