-- MAGIC %md
-- MAGIC ## Step 22 — Blue/green swap
-- MAGIC
-- MAGIC **Use when** rebuilding a table people are actively querying, and a half-finished
-- MAGIC state must never be visible.
-- MAGIC
-- MAGIC 1. Build the new version **beside** the live table
-- MAGIC 2. **Check it** — counts, totals, spot checks
-- MAGIC 3. **Swap the names** — instant, metadata only
-- MAGIC 4. Keep the old table as the rollback
-- MAGIC
-- MAGIC **Why bother, when Delta writes are already atomic?** Because the *checking* step is
-- MAGIC the point. A transaction guarantees the write completed; it does not guarantee the
-- MAGIC result is correct. Blue/green lets you inspect before anyone sees it, and makes
-- MAGIC rollback a rename rather than a restore.

-- COMMAND ----------

-- 1. Build alongside.
CREATE OR REPLACE TABLE orders_new AS
SELECT order_id, customer, upper(region) AS region, product,
       quantity, unit_price, order_date, status, discount_pct
FROM orders;

-- COMMAND ----------

-- MAGIC %md
-- MAGIC ### 2. Verify before swapping — the whole value of the pattern
-- MAGIC If these disagree you stop here, and nobody downstream ever knew.

-- COMMAND ----------

SELECT 'live' AS which, count(*) AS rows, sum(quantity * unit_price) AS revenue FROM orders
UNION ALL
SELECT 'new',           count(*),          sum(quantity * unit_price)           FROM orders_new;

-- COMMAND ----------

-- 3. Swap. Instant, metadata only. orders_old is the rollback.
ALTER TABLE orders     RENAME TO orders_old;
ALTER TABLE orders_new RENAME TO orders;

SELECT order_id, customer, region, status FROM orders ORDER BY order_id;

